"""Prepare leader-scoped text and route tables for the reviewed voice trials.

Sources and their status remain in full-game-inventory.json.  Preparing these
files does not assert that every engine route resolves or was tested in game.
"""
import hashlib
import json
from pathlib import Path

from lxml import etree

ROOT = Path(__file__).resolve().parents[1]
VOICE = ROOT / 'art/voice'
LEADER = 'LEADER_REMSELY_ALEXANDER_II'


def tag_for(row):
    key = row['key']
    if row['kind'] == 'reason':
        assert '_LEADER_ANY_REASON_' in key
        return key.replace('_LEADER_ANY_REASON_', '_' + LEADER + '_REASON_')
    if row['kind'] in ('deal_ui', 'statement_literal'):
        return key + '_REMSELY_ALEXANDER_II'
    assert row['kind'] == 'statement' and key.endswith('_ANY_ANY'), key
    base = key[:-len('_ANY_ANY')]
    if base.endswith('_LEADER'):
        base = base[:-len('_LEADER')]
    return base + '_' + LEADER + '_ANY'


def main():
    rows = json.loads((VOICE / 'full-game-inventory.json').read_text(encoding='utf-8'))
    en = json.loads((VOICE / 'full-game-english.json').read_text(encoding='utf-8'))
    en_source = json.loads((VOICE / 'full-game-english-source.json').read_text(encoding='utf-8'))
    assert len(rows) == 137 and {r['number'] for r in rows} == set(range(1, 138))
    assert set(en) == set(map(str, range(1, 138)))
    print('English source format:', type(en_source).__name__)
    for r in rows:
        n = str(r['number'])
        src = en_source[n]
        assert src['key'] == r['key'] and src['text_ru_sha256'] == hashlib.sha256(r['text_ru'].encode('utf-8')).hexdigest(), n
        assert hashlib.sha256((ROOT / r['file']).read_bytes()).hexdigest() == r['sha256'], n
        r['slot'] = 'FULL_%03d' % r['number']
        r['text_en'] = en[n]
        r['tag'] = tag_for(r)
    assert len({r['tag'] for r in rows}) == len(rows)
    (VOICE / 'full-game-manifest.json').write_text(json.dumps(rows, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    for language, field in (('ru_RU', 'text_ru'), ('en_US', 'text_en')):
        tree = etree.Element('GameData')
        local = etree.SubElement(tree, 'LocalizedText')
        for r in rows:
            node = etree.SubElement(local, 'Replace', Tag=r['tag'], Language=language)
            etree.SubElement(node, 'Text').text = r[field]
        etree.indent(tree, space='  ')
        etree.ElementTree(tree).write(str(ROOT / f'mod/Text/FullVoice_{language}.xml'), encoding='utf-8', xml_declaration=True, pretty_print=True)
    tables = {'statement': [], 'reason': [], 'deal_ui': []}
    for r in rows:
        kind = 'statement' if r['kind'] == 'statement_literal' else r['kind']
        lookup = r['key'] if kind == 'deal_ui' else r['tag']
        tables[kind].append((lookup, r['slot']))
    lines = ['-- Generated by tools/prepare_full_voice.py.']
    for kind, entries in tables.items():
        lines.append('REMSELY_FullVoice_' + kind + ' = {')
        lines.extend('    ["%s"] = "%s",' % pair for pair in entries)
        lines.append('};')
    (ROOT / 'mod/UI/RemselysAlexanderII_FullVoice.lua').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    sql = ['-- Clone only the three vanilla literal-key rows for this leader.']
    for r in rows:
        if r['kind'] != 'statement_literal':
            continue
        assert "'" not in r['key'] + r['tag']
        sql.append("""INSERT OR IGNORE INTO DiplomacyStatements
 (Type, SubType, Initiator, Leader, Mood, StatementText, ReasonText, LeaderAnimation, SceneEffect, Selections)
 SELECT Type, SubType, Initiator, '%s', Mood, '%s', ReasonText, LeaderAnimation, SceneEffect, Selections
 FROM DiplomacyStatements WHERE Leader = 'ANY' AND StatementText = '%s';""" % (LEADER, r['tag'], r['key']))
    (ROOT / 'mod/Data/FullVoice.sql').write_text('\n'.join(sql) + '\n', encoding='utf-8')
    print('Prepared', len(rows), 'records, with source hashes and leader-scoped translations.')


if __name__ == '__main__':
    main()
